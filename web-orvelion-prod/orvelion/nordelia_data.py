def get_cabang_by_id(cabang_id: str):
    if not cabang_id:
        return None
    cabang_clean = str(cabang_id).lower().replace("_", "-").strip()
    for c in CABANG_LOMBA:
        if c["id"] == cabang_id or c["id"] == cabang_clean:
            return c
    resolved_id = CABANG_ALIASES.get(cabang_id) or CABANG_ALIASES.get(cabang_clean)
    if resolved_id:
        for c in CABANG_LOMBA:
            if c["id"] == resolved_id:
                return c
    for c in CABANG_LOMBA:
        if c["name"].lower() == cabang_clean or c["name"].lower() == str(cabang_id).lower().strip():
            return c
    if ("ai" in cabang_clean or "artifisial" in cabang_clean) and not ("desain" in cabang_clean or "poster" in cabang_clean):
        for c in CABANG_LOMBA:
            if c["id"] == "olimpiade-ai":
                return c
    return None


def get_cabang_by_category(cat_id: str):
    if cat_id == "semua":
        return CABANG_LOMBA
    return [c for c in CABANG_LOMBA if c["category"] == cat_id]
